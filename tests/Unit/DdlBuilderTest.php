it('quotes reserved words, embedded quotes and unicode in identifiers', function () {
    expect(ddlSql(['op' => 'create_table', 'schema' => 'select', 'name' => 'user', 'columns' => [
        ['name' => 'we"ird', 'type' => 'text'],
        ['name' => 'café_日本', 'type' => 'text'],
        ['name' => 'order', 'type' => 'int'],
    ]]))->toBe(["CREATE TABLE \"select\".\"user\" (\n    \"we\"\"ird\" text,\n    \"café_日本\" text,\n    \"order\" integer\n)"])
        ->and(DdlBuilder::quoteIdentifier('"'))->toBe('""""')
        ->and(DdlBuilder::quoteIdentifier('a"; DROP TABLE x; --'))->toBe('"a""; DROP TABLE x; --"');
});

it('accepts identifiers of up to 63 bytes and rejects longer ones', function () {
    expect(DdlBuilder::quoteIdentifier(str_repeat('a', 63)))->toBe('"'.str_repeat('a', 63).'"')
        ->and(DdlBuilder::quoteIdentifier(str_repeat('日', 21)))->toBe('"'.str_repeat('日', 21).'"')
        ->and(ddlError(['op' => 'drop_table', 'schema' => 'app', 'name' => str_repeat('a', 64)]))->toBe('name')
        // 22 characters, but 66 bytes.
        ->and(ddlError(['op' => 'drop_table', 'schema' => 'app', 'name' => str_repeat('日', 22)]))->toBe('name');
});

it('rejects empty, NUL-containing and invalid UTF-8 identifiers', function (string $name) {
    expect(ddlError(['op' => 'drop_table', 'schema' => 'app', 'name' => $name]))->toBe('name')
        ->and(fn () => DdlBuilder::quoteIdentifier($name))->toThrow(ValidationException::class);
})->with([
    'empty' => '',
    'NUL' => "users\0; DROP TABLE x",
    'invalid UTF-8' => "users\xC3\x28",
]);

