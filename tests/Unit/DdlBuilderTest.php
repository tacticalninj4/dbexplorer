/**
 * A builder with a fake type resolver: a fixed map from input to canonical
 * spelling, standing in for validateType() (covered in tests/Pgsql).
 */
function ddlBuilder(): DdlBuilder
{
    return new DdlBuilder(fn (string $type, string $field): string => [
        'int' => 'integer',
        'bigint' => 'bigint',
        'text' => 'text',
        'boolean' => 'boolean',
        'varchar(255)' => 'character varying(255)',
        'numeric(10,2)' => 'numeric(10,2)',
        'timestamptz' => 'timestamp with time zone',
        'text[]' => 'text[]',
        'mood' => 'fixture.mood',
    ][$type] ?? throw ValidationException::withMessages([$field => 'The type does not exist.']));
}

/**
 * @param  array<string, mixed>  $op
 * @return list<string>
 */
function ddlSql(array $op): array
{
    return array_column(ddlBuilder()->build($op), 'sql');
}

/**
 * The field the ValidationException from building $op is keyed by, or null.
 *
 * @param  array<string, mixed>  $op
 */
function ddlError(array $op): ?string
{
    try {
        ddlBuilder()->build($op);
    } catch (ValidationException $e) {
        return (string) array_key_first($e->errors());
    }

    return null;
}

