it('emits only the canonical type the resolver returns, never the input', function () {
    $seen = [];
    $builder = new DdlBuilder(function (string $type, string $field) use (&$seen): string {
        $seen[] = [$type, $field];

        return 'character varying(255)';
    });

    $sql = $builder->build(['op' => 'add_column', 'schema' => 'app', 'table' => 't', 'column' => ['name' => 'a', 'type' => 'VARCHAR ( 255 )']])[0]['sql'];

    expect($sql)->toBe('ALTER TABLE "app"."t" ADD COLUMN "a" character varying(255)')
        ->and($seen)->toBe([['VARCHAR ( 255 )', 'column.type']]);
});

it('classifies drops and type changes as destructive and everything else as ddl', function () {
    $classification = fn (array $op): string => ddlBuilder()->build($op)[0]['classification'];

    foreach ([
        ['op' => 'drop_table', 'schema' => 'a', 'name' => 't'],
        ['op' => 'drop_column', 'schema' => 'a', 'table' => 't', 'name' => 'c'],
        ['op' => 'drop_index', 'schema' => 'a', 'name' => 'i'],
        ['op' => 'drop_constraint', 'schema' => 'a', 'table' => 't', 'name' => 'c'],
        ['op' => 'drop_view', 'schema' => 'a', 'name' => 'v'],
        ['op' => 'drop_materialized_view', 'schema' => 'a', 'name' => 'v'],
        ['op' => 'alter_column_type', 'schema' => 'a', 'table' => 't', 'name' => 'c', 'type' => 'text'],
    ] as $op) {
        expect($classification($op))->toBe(DdlBuilder::DESTRUCTIVE, $op['op']);
    }

    foreach ([
        ['op' => 'create_table', 'schema' => 'a', 'name' => 't', 'columns' => [['name' => 'c', 'type' => 'text']]],
        ['op' => 'rename_table', 'schema' => 'a', 'name' => 't', 'to' => 'u'],
        ['op' => 'add_column', 'schema' => 'a', 'table' => 't', 'column' => ['name' => 'c', 'type' => 'text']],
        ['op' => 'drop_default', 'schema' => 'a', 'table' => 't', 'name' => 'c'],
        ['op' => 'drop_not_null', 'schema' => 'a', 'table' => 't', 'name' => 'c'],
        ['op' => 'create_index', 'schema' => 'a', 'table' => 't', 'columns' => ['c']],
        ['op' => 'create_view', 'schema' => 'a', 'name' => 'v', 'body' => 'SELECT 1'],
        ['op' => 'refresh_materialized_view', 'schema' => 'a', 'name' => 'v'],
    ] as $op) {
        expect($classification($op))->toBe(DdlBuilder::DDL, $op['op']);
    }
});

it('marks CONCURRENTLY index statements as not transactional', function () {
    $index = ['op' => 'create_index', 'schema' => 'a', 'table' => 't', 'columns' => ['c']];

    expect(ddlBuilder()->build($index)[0]['transactional'])->toBeTrue()
        ->and(ddlBuilder()->build($index + ['concurrently' => true])[0]['transactional'])->toBeFalse()
        ->and(ddlBuilder()->build(['op' => 'drop_index', 'schema' => 'a', 'name' => 'i', 'concurrently' => true])[0]['transactional'])->toBeFalse()
        // REFRESH ... CONCURRENTLY is allowed in a transaction.
        ->and(ddlBuilder()->build(['op' => 'refresh_materialized_view', 'schema' => 'a', 'name' => 'v', 'concurrently' => true])[0]['transactional'])->toBeTrue();
});

it('flags statements that carry raw SQL expressions', function () {
    $raw = fn (array $op): array => array_column(ddlBuilder()->build($op), 'raw_expressions');

    expect($raw(['op' => 'create_table', 'schema' => 'a', 'name' => 't', 'comment' => 'x', 'columns' => [['name' => 'c', 'type' => 'int', 'default' => '1']]]))->toBe([true, false])
        ->and($raw(['op' => 'create_table', 'schema' => 'a', 'name' => 't', 'columns' => [['name' => 'c', 'type' => 'int']]]))->toBe([false])
        ->and($raw(['op' => 'create_index', 'schema' => 'a', 'table' => 't', 'columns' => ['c'], 'where' => 'c > 0']))->toBe([true])
        ->and($raw(['op' => 'create_index', 'schema' => 'a', 'table' => 't', 'expression' => 'lower(c)']))->toBe([true])
        ->and($raw(['op' => 'alter_column_type', 'schema' => 'a', 'table' => 't', 'name' => 'c', 'type' => 'int', 'using' => 'c::int']))->toBe([true])
        ->and($raw(['op' => 'alter_column_type', 'schema' => 'a', 'table' => 't', 'name' => 'c', 'type' => 'int']))->toBe([false])
        ->and($raw(['op' => 'create_view', 'schema' => 'a', 'name' => 'v', 'body' => 'SELECT 1']))->toBe([true])
        ->and($raw(['op' => 'drop_table', 'schema' => 'a', 'name' => 't']))->toBe([false]);

    // The flag doesn't leak from one build to the next.
    $builder = ddlBuilder();
    $builder->build(['op' => 'create_view', 'schema' => 'a', 'name' => 'v', 'body' => 'SELECT 1']);

    expect($builder->build(['op' => 'drop_view', 'schema' => 'a', 'name' => 'v'])[0]['raw_expressions'])->toBeFalse();
});

it('quotes literals safely whatever standard_conforming_strings is', function () {
    expect(DdlBuilder::quoteLiteral("it's"))->toBe("'it''s'")
        ->and(DdlBuilder::quoteLiteral('a\\\'b'))->toBe("E'a\\\\''b'")
        ->and(DdlBuilder::quoteLiteral('日本'))->toBe("'日本'");
});

it('writes a Laravel migration snippet for simple create table and add column operations', function () {
    $create = ddlBuilder()->toMigrationSnippet(['op' => 'create_table', 'schema' => 'app', 'name' => 'users', 'columns' => [
        ['name' => 'id', 'type' => 'bigint', 'identity' => 'by_default', 'primary' => true],
        ['name' => 'email', 'type' => 'varchar(255)', 'nullable' => false, 'unique' => true],
        ['name' => 'balance', 'type' => 'numeric(10,2)', 'nullable' => false, 'default' => '0'],
        ['name' => 'seen_at', 'type' => 'timestamptz', 'comment' => "It's when"],
    ]]);

    expect($create)->toBe(<<<'PHP'
        Schema::create('app.users', function (Blueprint $table) {
            $table->bigIncrements('id');
            $table->string('email', 255)->unique();
            $table->decimal('balance', 10, 2)->default(DB::raw('0'));
            $table->timestampTz('seen_at', null)->nullable()->comment('It\'s when');
        });
        PHP)
        ->and(ddlBuilder()->toMigrationSnippet(['op' => 'add_column', 'schema' => 'app', 'table' => 'users', 'column' => ['name' => 'active', 'type' => 'boolean', 'nullable' => false]]))
        ->toBe("Schema::table('app.users', function (Blueprint \$table) {\n    \$table->boolean('active');\n});")
        ->and(ddlBuilder()->toMigrationSnippet(['op' => 'add_column', 'schema' => 'app', 'table' => 'users', 'column' => ['name' => "o'k\\", 'type' => 'text', 'default' => "'a\\b'"]]))
        ->toBe("Schema::table('app.users', function (Blueprint \$table) {\n    \$table->text('o\\'k\\\\')->nullable()->default(DB::raw('\\'a\\\\b\\''));\n});")
        ->and(ddlBuilder()->toMigrationSnippet(['op' => 'add_column', 'schema' => 'app', 'table' => 'codes', 'column' => ['name' => 'code', 'type' => 'text', 'primary' => true]]))
        ->toBe("Schema::table('app.codes', function (Blueprint \$table) {\n    \$table->text('code')->primary();\n});");
});

